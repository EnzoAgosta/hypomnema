# Fuzz: independently generated valid trees are accepted; structural
# mutations of valid trees are rejected; nothing escapes ValidationError.


def _random_valid_flow(rng: random.Random, depth: int, counter: Iterator[int]) -> tuple[Any, ...]:
  """Build a tree that satisfies decision 12 by construction: one shared
  ``i`` counter per flow (shared through <hi>, fresh for <sub>)."""
  items: list[Any] = []
  for _ in range(rng.randint(0, 4)):
    kind = rng.random()
    if kind < 0.25 or depth <= 0:
      items.append(f"text{rng.randint(0, 99)}")
    elif kind < 0.45:  # adjacent pair whose bpt carries sub flows
      i = next(counter)
      sub_count = rng.randint(1, 2)
      sub_flows = tuple(Sub(content=_random_valid_flow(rng, depth - 1, itertools.count(1))) for _ in range(sub_count))
      items.append(Bpt(i=i, content=sub_flows))
      items.append(Ept(i=i, content=sub_flows if rng.random() < 0.3 else ()))
    elif kind < 0.65:  # wrapping pair; the wrapped flow shares the namespace
      i = next(counter)
      items.append(Bpt(i=i))
      items.extend(_random_valid_flow(rng, depth - 1, counter))
      items.append(Ept(i=i))
    elif kind < 0.8:  # transparent highlight
      items.append(Hi(content=_random_valid_flow(rng, depth - 1, counter)))
    else:  # placeholder tag carrying its own sub flow
      sub_flow = _random_valid_flow(rng, depth - 1, itertools.count(1))
      if rng.random() < 0.5:
        items.append(It(pos=rng.choice(["begin", "end"]), content=(Sub(content=sub_flow),)))
      elif rng.random() < 0.5:
        items.append(Ph(content=(Sub(content=sub_flow),)))
      else:
        items.append(Ut(content=(Sub(content=sub_flow),)))
  return tuple(items)


def test_fuzz_valid_trees_are_accepted() -> None:
  rng = random.Random(424242)
  with warnings.catch_warnings():
    warnings.simplefilter("ignore")
    for _ in range(300):
      content = _random_valid_flow(rng, depth=3, counter=itertools.count(1))
      validate_translation_unit_variant(TranslationUnitVariant(xml_lang="en", content=as_generated(content)))


def as_generated(content: tuple[Any, ...]) -> Any:
  """A generated list/tuple of models the static checker must not judge."""
  return content


def _random_any_flow(rng: random.Random, depth: int) -> tuple[Any, ...]:
  """Like the valid generator but with independent random i values, so
  duplicates, orphans, and crossings occur naturally."""
  items: list[Any] = []
  for _ in range(rng.randint(0, 4)):
    kind = rng.random()
    if kind < 0.3 or depth <= 0:
      items.append(f"text{rng.randint(0, 99)}")
    elif kind < 0.55:
      i = rng.randint(0, 4)
      sub_count = rng.randint(1, 2)
      sub_flows = tuple(Sub(content=_random_any_flow(rng, depth - 1)) for _ in range(sub_count))
      items.append(Bpt(i=i, content=sub_flows))
      if rng.random() < 0.8:
        items.append(Ept(i=rng.randint(0, 4), content=sub_flows if rng.random() < 0.3 else ()))
    elif kind < 0.7:
      items.extend(_random_any_flow(rng, depth - 1))
    elif kind < 0.85:
      items.append(Hi(content=_random_any_flow(rng, depth - 1)))
    else:
      sub_flow = _random_any_flow(rng, depth - 1)
      if rng.random() < 0.5:
        items.append(It(pos=rng.choice(["begin", "end"]), content=(Sub(content=sub_flow),)))
      else:
        items.append(Ut(content=(Sub(content=sub_flow),)))
  return tuple(items)


def _all_epts(node: Any) -> list[Ept]:
  if isinstance(node, Ept):
    return [node]
  if isinstance(node, str):
    return []
  found: list[Ept] = []
  for child in node.content:
    found.extend(_all_epts(child))
  return found


def test_fuzz_rejections_never_escape_validation_error() -> None:
  rng = random.Random(909)
  with warnings.catch_warnings():
    warnings.simplefilter("ignore")
    for _ in range(500):
      content = _random_any_flow(rng, depth=3)
      try:
        validate_translation_unit_variant(TranslationUnitVariant(xml_lang="en", content=as_generated(content)))
      except ValidationError:
        continue
      # No other exception type may escape; acceptance is covered by the
      # valid-tree and mutation tests.


def test_mutating_a_valid_tree_is_always_rejected() -> None:
  rng = random.Random(31337)
  with warnings.catch_warnings():
    warnings.simplefilter("ignore")
    for _ in range(300):
      content = _random_valid_flow(rng, depth=3, counter=itertools.count(1))
      epts = [node for node in _iter_nodes(content) if isinstance(node, Ept)]
      if not epts:
        continue
      victim = rng.choice(epts)
      mutation = rng.choice(["drop", "renumber", "duplicate_bpt"])
      if mutation == "drop":
        broken = _drop_node(content, victim)
      elif mutation == "renumber":
        victim.i = rng.randint(1000, 2000)  # mutates in place, detaching the pair
        broken = content
      else:
        broken = _insert_after(content, victim, Bpt(i=victim.i))
      with pytest.raises(ValidationError) as excinfo:
        validate_translation_unit_variant(TranslationUnitVariant(xml_lang="en", content=as_generated(broken)))
      assert all(error["type"] == "inline_tag_pairing" for error in excinfo.value.errors())


def _iter_nodes(items: tuple[Any, ...]) -> Iterator[Any]:
  for node in items:
    if isinstance(node, str):
      continue
    yield node
    for child in _iter_nodes(node.content):
      yield child


def _drop_node(items: tuple[Any, ...], victim: Ept) -> tuple[Any, ...]:
  kept: list[Any] = []
  for node in items:
    if node is victim:
      continue
    if isinstance(node, str):
      kept.append(node)
    else:
      kept.append(type(node).model_construct(**{**node.model_dump(), "content": _drop_node(node.content, victim)}))
  return tuple(kept)


def _insert_after(items: tuple[Any, ...], after: Ept, node: Bpt) -> tuple[Any, ...]:
  rebuilt: list[Any] = []
  for item in items:
    if isinstance(item, str):
      rebuilt.append(item)
      continue
    if item is after:
      rebuilt.append(item)
      rebuilt.append(node)
    else:
      rebuilt.append(
        type(item).model_construct(**{**item.model_dump(), "content": _insert_after(item.content, after, node)})
      )
  return tuple(rebuilt)
