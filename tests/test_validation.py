# Rejection: unmatched, orphaned, and duplicated i, with locations.


def test_unmatched_bpt_is_rejected() -> None:
  error = expect_pairing_error(
    lambda: validate_translation_unit_variant(tuv(Bpt(i=1), "text")), "no subsequent corresponding <ept>"
  )
  assert error.errors()[0]["loc"] == ("content", 0)


def test_orphan_ept_is_rejected() -> None:
  error = expect_pairing_error(lambda: validate_translation_unit_variant(tuv("a", Ept(i=1))), "no corresponding <bpt>")
  assert error.errors()[0]["loc"] == ("content", 1)


def test_ept_before_its_bpt_is_rejected_as_orphan() -> None:
  expect_pairing_error(lambda: validate_translation_unit_variant(tuv(Ept(i=1), Bpt(i=1))), "no corresponding <bpt>")


def test_duplicate_bpt_i_is_rejected() -> None:
  error = expect_pairing_error(
    lambda: validate_translation_unit_variant(tuv(Bpt(i=1), Bpt(i=1))), "duplicate <bpt> i=1"
  )
  assert error.errors()[0]["loc"] == ("content", 1)


def test_duplicate_ept_i_is_rejected() -> None:
  error = expect_pairing_error(
    lambda: validate_translation_unit_variant(tuv(Bpt(i=1), Ept(i=1), Ept(i=1))), "duplicate <ept> i=1"
  )
  assert error.errors()[0]["loc"] == ("content", 2)


def test_duplicate_i_inside_a_sub_flow_does_not_spill_into_the_outer_flow() -> None:
  dup_sub = Sub(content=(Bpt(i=1), Bpt(i=1)))
  error = expect_pairing_error(
    lambda: validate_translation_unit_variant(tuv(Bpt(i=1, content=(dup_sub,)))), "duplicate <bpt> i=1"
  )
  # loc reaches into the sub flow: bpt > content[0] > sub > content[1]
  assert error.errors()[0]["loc"] == ("content", 0, "content", 0, "content", 1)


def test_an_ept_in_one_sub_does_not_close_a_bpt_in_the_enclosing_flow() -> None:
  sibling_sub = Sub(content=("a", Ept(i=1)))
  with pytest.raises(ValidationError) as excinfo:
    validate_translation_unit_variant(tuv(Bpt(i=1, content=(sibling_sub,))))
  messages = [error["msg"] for error in excinfo.value.errors()]
  assert len(messages) == 2
  assert any("no corresponding <bpt>" in message for message in messages)  # the sub-flow orphan
  assert any("no subsequent corresponding <ept>" in message for message in messages)  # the outer bpt


def test_errors_aggregate() -> None:
  with pytest.raises(ValidationError) as excinfo:
    validate_translation_unit_variant(tuv(Bpt(i=1), Bpt(i=1), Ept(i=3)))
  assert len(excinfo.value.errors()) == 3


def test_a_valid_flow_inside_an_invalid_variant_is_not_reported() -> None:
  # Only the broken flow produces an error, and its loc points at it.
  broken_sub = Sub(content=("s", Bpt(i=2)))
  good_sub = Sub(content=(Bpt(i=3), Ept(i=3)))
  with pytest.raises(ValidationError) as excinfo:
    validate_translation_unit_variant(tuv(Bpt(i=1, content=(good_sub, broken_sub)), Ept(i=1)))
  assert len(excinfo.value.errors()) == 1
  assert excinfo.value.errors()[0]["loc"] == ("content", 0, "content", 1, "content", 1)


